import sys, time, os, json
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from launch import *
from tour import *

OUT = "/home/user/log/media/2026-11-12/tour"
L = SceneScript("construct", "scene-construct.sh", "light")
S = Session(L.env, L.pids, BIN)
t = Tour(S, OUT, f"{L.dir}/work")
t.begin("4 construct", "04-construct")
try:
    t.jump(640, 360)
    t.wait(2)
    t.act("look", "Look at the construct", "A pale sky over a marble floor, three panes ahead, HUD chips", still="04-01-start")
    t.done()
    t.act("key", "Hold w for 2 s (walk forward)", "The camera walks forward, the panes grow", settle=0.5, still="04-02-walk-forward")
    t.hold("w", 2.0); t.done()
    t.act("key", "Hold e for 1.2 s (turn right)", "The view turns right toward the chora pane", settle=0.5, still="04-03-turn-right")
    t.hold("e", 1.2); t.done()
    t.act("key", "Hold q for 2.4 s (turn left)", "The view turns left toward the wobbly.rs pane", settle=0.5, still="04-04-turn-left")
    t.hold("q", 2.4); t.done()
    t.act("key", "Hold e for 1.2 s (back to the middle)", "The sunset pane is in the middle again", settle=0.5, still="04-05-turn-back")
    t.hold("e", 1.2); t.done()
    t.act("key", "Hold s for 1.5 s (walk back)", "The camera walks back", settle=0.5, still="04-06-walk-back")
    t.hold("s", 1.5); t.done()
    t.act("key", "Press Return (fly in)", "The camera flies into the pane in the middle; the window shows 1:1", settle=3.0, still="04-07-fly-in")
    t.key("Return"); t.done()
    t.act("key", "Press Alt+Escape (fly out)", "The camera flies back out to the pose before", settle=3.0, still="04-08-fly-out")
    t.key("Alt+Escape"); t.done()
    t.act("key", "Press Tab (window list)", "A glass list shows the five windows, hidden ones marked not in view", settle=1.5, still="04-09-window-list")
    t.key("Tab"); t.done()
    t.act("key", "Press Down twice", "The selection moves down two rows", settle=0.8, still="04-10-list-down")
    t.key("Down"); t.wait(0.5); t.key("Down"); t.done()
    t.act("key", "Press Return (choose)", "The camera flies to the chosen pane", settle=3.5, still="04-11-list-choice")
    t.key("Return"); t.done()
    t.act("key", "Press Alt+Escape (fly out)", "The camera flies back out", settle=3.0, still="04-12-fly-out-2")
    t.key("Alt+Escape"); t.done()
    t.act("key", "Press F1 (help)", "A glass help panel lists the keys", settle=1.5, still="04-13-help")
    t.key("F1"); t.done()
    t.act("key", "Press F1 again", "The help panel hides", settle=1.2, still="04-14-help-gone")
    t.key("F1"); t.done()
    t.act("key", "Press z (a key that does nothing)", "A notice: The keys walk here. F1 shows them all.", settle=1.0, still="04-15-notice")
    t.key("z"); t.done()
    t.wait(1.5)
    t.finish("04-construct.mp4")
    json.dump(t.rows, open(f"{OUT}/rows-ch4.json", "w"), indent=1)
finally:
    L.stop()
