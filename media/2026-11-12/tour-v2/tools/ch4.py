import sys, time, os, json
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from cons import *
from tour import *
from slides import slide

OUT = "/home/user/log/media/2026-11-12/tour-v2"
L, S = start_construct("light", "construct")
t = Tour(S, OUT, f"{L.dir}/work")
t.begin("4 construct", "04-construct")
O = "HEADLESS-1"
try:
    t.jump(640, 400)
    t.wait(1.2)
    t.act("look", "The construct", "Pale sky, marble floor, three panes ahead; no HUD while the voice agent is silent", still="04-01-start")
    t.done()
    t.act("key", "Hold w for 1.5 s (walk forward)", "The camera walks forward, the panes grow", settle=0.4, still="04-02-walk-forward")
    t.hold("w", 1.5); t.done()
    t.act("key", "Hold e for 1 s (turn right)", "The view turns to the right", settle=0.4, still="04-03-turn-right")
    t.hold("e", 1.0); t.done()
    t.act("key", "Hold q for 1 s (turn back)", "The view turns back to the middle", settle=0.4, still="04-04-turn-left")
    t.hold("q", 1.0); t.done()
    t.act("key", "Press Return (fly in)", "The camera flies into the pane ahead; it shows at 1:1", settle=2.5, still="04-05-fly-in")
    t.key("Return"); t.done()
    t.act("key", "Press Alt+Escape (fly out)", "The camera flies back out", settle=2.5, still="04-06-fly-out")
    t.key("Alt+Escape"); t.done()
    t.act("key", "Press Super+t (open a terminal)", "A terminal opens as a pane and the camera flies into it", settle=6.0, still="04-07-terminal")
    t.key("Super+t"); t.done()
    t.act("keys", "Type cat friday.md", "The shell prints the Friday list", settle=0.6, still="04-08-cat")
    t.text("cat friday.md\n"); t.done()
    t.act("key", "Press Alt+Escape (fly out)", "The camera flies out; the terminal is a pane among the others", settle=2.5, still="04-09-terminal-pane")
    t.key("Alt+Escape"); t.done()
    t.act("key", "Press Tab (window list)", "A list shows the five windows (now six) with thumbnails and where each is", settle=1.2, still="04-10-window-list")
    t.key("Tab"); t.done()
    t.act("key", "Press Down twice", "The selection moves down two rows", settle=0.6, still="04-11-list-down")
    t.key("Down"); t.wait(0.3); t.key("Down"); t.done()
    t.act("key", "Press Return (choose)", "The camera flies to the chosen window", settle=3.0, still="04-12-list-choice")
    t.key("Return"); t.done()
    t.act("key", "Press Alt+Escape (fly out)", "The camera flies back out", settle=2.5, still="04-13-fly-out-2")
    t.key("Alt+Escape"); t.done()
    t.act("key", "Press F1 (key overlay)", "A searchable list of the keys that work now", settle=1.2, still="04-14-keys")
    t.key("F1"); t.done()
    t.act("keys", "Type 'turn' into the search", "The list narrows to the turn keys", settle=0.8, still="04-15-keys-search")
    t.text("turn"); t.done()
    t.act("key", "Press Escape (clears the search)", "The first Escape clears the search text and keeps the list", settle=0.8, still="04-16-keys-cleared")
    t.key("Escape"); t.done()
    t.act("key", "Press Escape again", "The overlay closes", settle=1.0, still="04-16b-keys-closed")
    t.key("Escape"); t.done()
    t.act("key", "Press z (a key that does nothing)", "A notice in the HUD says what the keys do here", settle=1.0, still="04-17-notice")
    t.key("z"); t.done()
    t.flush("voice")
    L.emit("voice.state", {"state": "listening", "task": "", "said": ""})
    t.wait(0.8)
    t.flush("voice-say")
    L.emit("voice.say", {"text": "Good morning! Your notes for Friday are ready.", "duration_ms": 8000})
    L.emit("voice.state", {"name": "Atlas", "state": "working", "task": "Tidy notes", "step": 1, "steps": 2, "seq": 4})
    t.act("voice event", "The fake voice agent says: Good morning! Your notes for Friday are ready.", "The HUD island at the top right shows the sentence", settle=2.0, still="04-18-hud-sentence", lead=0.3)
    t.done()
    t.wait(1.5)
    ix, iy = None, None
    t.flush("island")
    ix, iy = S.centre("id:hud-figure", O)
    t.act("pointer", "Click the HUD island", "The chat opens as a glass panel at the right with the field focused", settle=1.8, still="04-19-chat-open")
    t.move(ix, iy); t.click(); t.done()
    t.act("keys", "Type 1 and press Return (pick Atlas)", "Atlas is picked: state, task and transcript", settle=1.5, still="04-20-picked")
    t.text("1"); t.key("Return"); t.done()
    msg = "Please also add Monday."
    t.act("keys", f"Type '{msg}' and press Return", "The message is sent and shows as a bubble", settle=1.2, still="04-21-sent")
    t.text(msg); t.key("Return"); t.done()
    t.flush("question")
    L.emit("voice.state", {"name": "Atlas", "state": "question", "task": "Tidy notes", "seq": 5})
    L.emit("voice.confirm", {"id": "51", "prompt": "Atlas wants to write the file notes.txt.", "detail": "~/notes/friday-summary.txt (412 bytes)", "physical": True, "keys": {"yes": "Alt+y", "no": "Alt+n"}, "buttons": True})
    t.wait(1.5)
    t.act("voice event", "The helper asks: Atlas wants to write the file notes.txt", "A question card with Yes and No, Alt+Y and Alt+N", settle=1.0, still="04-22-question")
    t.done()
    t.flush("card")
    yx, yy = S.centre("id:hud-card-yes", O)
    t.act("pointer", "Click Yes", "The click answers the question", settle=1.2, still="04-23-yes")
    t.move(yx, yy); t.click(); t.done()
    t.flush("answered")
    L.emit("voice.confirm", {"id": "51", "done": True})
    L.emit("voice.state", {"name": "Atlas", "state": "working", "task": "Tidy notes", "step": 2, "steps": 2, "seq": 6})
    t.act("voice event", "The fake agent closes the question", "The card goes; the helper goes on", settle=1.2, still="04-24-card-closed")
    t.done()
    t.act("key", "Press Ctrl+. (stop the helper)", "The helper is stopped", settle=1.5, still="04-25-stop")
    t.key("Ctrl+period"); t.done()
    t.act("key", "Press Escape (close the chat)", "The chat closes", settle=1.5, still="04-26-chat-closed")
    t.key("Escape"); t.done()
    t.wait(0.5)
    slide(f"{L.dir}/slide.png", 4, "construct", ["A 3D space with panes instead of windows.", "Walk, turn, fly into a pane, the window list,", "the key overlay and the voice HUD with its chat."], accent=(187, 154, 247))
    t.finish("04-construct.mp4", slide=f"{L.dir}/slide.png")
    json.dump(t.rows, open(f"{OUT}/rows-ch4.json", "w"), indent=1)
finally:
    L.stop()
