import sys, time, os, json
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from launch import *
from tour import *
from slides import slide

OUT = "/home/user/log/media/2026-11-12/tour-v3"
L = Launcher("xp")
stub = f"{L.dir}/stub"; os.makedirs(stub, exist_ok=True)
yaml = open(f"{REPO}/plugins/chora-xp/xp.yaml").read().replace("sounds: true", "sounds: false").replace("programs: []", programs_yaml(stub)).replace("test_accept_injected_keys: false", "test_accept_injected_keys: true")
open(f"{L.dir}/xp.yaml", "w").write(yaml)
env = L.start([f"{BIN}/chora-xp", "--theme", f"{REPO}/flavors/xp/theme", "--config", f"{L.dir}/xp.yaml"], flavor="xp", xp=True,
              companions=[[f"{BIN}/chora-notify", "--assets", f"{REPO}/flavors/xp/assets/notify"], [f"{BIN}/chora-assistant"]])
S = Session(env, L.pids, BIN)
time.sleep(6)
t = Tour(S, OUT, f"{L.dir}/work")
t.begin("1 xp", "01-xp")
O = "HEADLESS-1"
try:
    def aim(sel, dx=0, dy=0):
        t.flush("aim")
        c = S.centre(sel, O)
        if c is None:
            raise RuntimeError("no node " + sel)
        return c[0] + dx, c[1] + dy

    def menu_item(n):
        t.flush("items")
        r = S.rect(f"id:xp-item-{n}", O)
        return r[0] + r[2] / 2, r[1] + r[3] / 2

    t.jump(640, 300)
    t.wait(1.2)
    t.act("look", "The xp desktop", "Bliss desktop, taskbar with Start, four desktop buttons, volume 40%, clock", still="01-01-desktop")
    t.done()
    sx, sy = aim("id:xp-start-HEADLESS-1")
    t.act("pointer", "Click Start", "The Start menu opens: Terminal, four programs, All Programs", still="01-02-start-menu")
    t.move(sx, sy); t.click(); t.done()
    x, y = menu_item(0)
    t.act("pointer", "Click Terminal", "A terminal window opens with a shell and a task button", settle=2.5, still="01-03-terminal-open")
    t.move(x, y); t.click(); t.done()
    t.act("keys", "Type ls, then cat friday.md", "The shell lists the notes and prints the Friday list", settle=0.8, still="01-04-shell")
    t.text("ls\n"); t.wait(0.5); t.text("cat friday.md\n"); t.done()
    sx, sy = aim("id:xp-start-HEADLESS-1")
    t.act("pointer", "Start, then Notes", "A Notes window opens over the terminal, a second task button", settle=3.0, still="01-05-notes-open")
    t.move(sx, sy); t.click(); t.wait(0.5)
    x, y = menu_item(1)
    t.move(x, y); t.click(); t.done()
    t.flush("notes")
    tx, ty = S.centre("id:xp-title-s2", O)
    t.act("pointer", "Drag the title bar of Notes to the right", "The window follows and bends like jelly, then settles", settle=0.3, still=None)
    t.drag(tx, ty, tx + 420, ty + 120, seconds=1.4, hold=0.1, mid_still="01-06-wobbly-drag")
    t.wait(0.6); t.done()
    bx, by = aim("id:xp-task-s1-HEADLESS-1")
    t.act("pointer", "Click the terminal button on the taskbar", "The terminal comes to the front", still="01-07-taskbar-terminal")
    t.move(bx, by); t.click(); t.done()
    t.act("pointer", "Click the speaker in the tray", "Volume mutes: the tray says Muted", still="01-08-muted")
    t.move(1155, 705); t.click(); t.done()
    t.act("pointer", "Click the speaker again", "Volume comes back to 40%", still="01-09-unmuted")
    t.click(); t.done()
    t.flush("before voice")
    L.emit("voice.state", {"state": "listening", "task": "", "said": ""})
    t.wait(0.6)
    t.flush("emit"); L.emit("voice.say", {"text": "Good morning! Your notes for Friday are ready.", "duration_ms": 9000})
    t.act("voice event", "The fake voice agent says: Good morning! Your notes for Friday are ready.", "The paperclip appears with a balloon of that sentence", settle=2.0, still="01-10-paperclip-balloon", lead=0.3)
    t.done()
    t.flush("emit2"); L.emit("voice.state", {"name": "Atlas", "state": "working", "task": "Tidy notes", "step": 1, "steps": 2, "seq": 4})
    t.wait(4)
    px, py = aim("id:hud-figure", 0, 10)
    t.act("pointer", "Click the paperclip", "The balloon becomes the chat: Chat with a helper, 1 Atlas working, a field", settle=1.5, still="01-11-chat-open")
    t.move(px, py); t.click(); t.done()
    cx, cy = aim("id:hud-chat-close")
    t.act("pointer", "Click Close", "The chat closes; only the paperclip stays", settle=1.2, still="01-12-chat-collapsed")
    t.move(cx, cy); t.click(); t.done()
    px, py = aim("id:hud-figure", 0, 10)
    t.act("pointer", "Click the paperclip again", "The chat opens again", settle=1.2, still="01-13-chat-reopened")
    t.move(px, py); t.click(); t.done()
    pk, pky = aim("id:hud-chat-pick-1")
    t.act("pointer", "Click the row 1 Atlas", "Atlas is picked; its transcript shows", settle=1.5, still="01-14-helper-picked")
    t.move(pk, pky); t.click(); t.done()
    t.flush("picked")
    r = S.rect("id:hud-chat", O)
    fx, fy = r[0] + r[2] / 2, r[1] + r[3] - 52
    t.act("pointer", "Click into the message field", "The field takes the keyboard (caret)", still="01-15-field-click")
    t.move(fx, fy); t.click(); t.done()
    msg = "Please also add Monday."
    t.act("keys", f"Type '{msg}'", "The text shows in the field", settle=0.5, still="01-16-typed")
    t.text(msg); t.done()
    t.act("key", "Press Return", "The message is sent: the field empties", settle=1.2, still="01-17-sent")
    t.key("Return"); t.done()
    t.flush("question")
    L.emit("voice.state", {"name": "Atlas", "state": "question", "task": "Tidy notes", "seq": 5})
    L.emit("voice.confirm", {"id": "51", "prompt": "Atlas wants to write the file notes.txt.", "detail": "~/notes/friday-summary.txt (412 bytes)", "physical": True, "keys": {"yes": "Alt+y", "no": "Alt+n"}, "buttons": True})
    t.wait(1.5)
    t.act("voice event", "The helper asks: Atlas wants to write the file notes.txt", "A question card with Yes and No shows in the chat", settle=1.0, still="01-18-question")
    t.done()
    yx, yy = aim("id:hud-card-yes")
    t.act("pointer", "Click Yes on the card", "The click answers the question", settle=1.5, still="01-19-answered")
    t.move(yx, yy); t.click(); t.done()
    t.flush("answered")
    L.emit("voice.confirm", {"id": "51", "done": True})
    L.emit("voice.state", {"name": "Atlas", "state": "working", "task": "Tidy notes", "step": 2, "steps": 2, "seq": 6})
    t.act("voice event", "The fake agent takes the answer and closes the question", "The card goes, the chat is back with the field", settle=1.2, still="01-19b-card-closed")
    t.done()
    t.act("key", "Press F1", "Key overlay (if xp has one)", settle=1.0, still="01-20-f1")
    t.key("F1"); t.done()
    t.wait(0.5)
    slide(f"{L.dir}/slide.png", 1, "xp", ["A Windows XP desktop on chora.", "Start menu, terminal, windows that wobble, the taskbar,", "the volume and the paperclip helper with its chat."])
    t.finish("01-xp.mp4", slide=f"{L.dir}/slide.png")
    json.dump(t.rows, open(f"{OUT}/rows-ch1.json", "w"), indent=1)
finally:
    L.stop()
