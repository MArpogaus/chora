import sys, time, os, json
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from launch import *
from human import Human
from tour import Session
from slides import slide

OUT = os.environ.get("TOUR_OUT", "/home/user/log/media/2026-11-16/tour-v3")
L = Launcher("xp")
stub = f"{L.dir}/stub"; os.makedirs(stub, exist_ok=True)
yaml = open(f"{REPO}/plugins/chora-xp/xp.yaml").read().replace("sounds: true", "sounds: false").replace("programs: []", programs_yaml(stub)).replace("test_accept_injected_keys: false", "test_accept_injected_keys: true")
open(f"{L.dir}/xp.yaml", "w").write(yaml)
env = L.start([f"{BIN}/chora-xp", "--theme", f"{REPO}/flavors/xp/theme", "--config", f"{L.dir}/xp.yaml"], flavor="xp", xp=True,
              companions=[[f"{BIN}/chora-notify", "--assets", f"{REPO}/flavors/xp/assets/notify"], [f"{BIN}/chora-assistant"]])
S = Session(env, L.pids, BIN)
time.sleep(6)
t = Human(S, OUT, f"{L.dir}/work")
t.begin("1 xp", "01-xp")
O = "HEADLESS-1"
try:
    def aim(sel, dx=0, dy=0):
        t.flush("aim")
        c = S.centre(sel, O)
        if c is None:
            raise RuntimeError("no node " + sel)
        return c[0] + dx, c[1] + dy

    t.jump(660, 330)
    t.wait(1.5)
    t.act("look", "The person sits down at the xp desktop and looks around", "Desktop picture, taskbar with Start, four desktop buttons, volume, clock", still="01-01-desktop", lead=0.2, settle=2.5)
    t.done()
    sx, sy = aim("id:xp-start-HEADLESS-1")
    t.act("pointer", "Move to Start and click it", "The Start menu opens: Terminal, Chat with a helper, four programs", still="01-02-start-menu", lead=0.3)
    t.reach(sx, sy); t.click(); t.wait(0.6); t.done()
    x, y = aim("id:xp-item-0")
    t.act("pointer", "Pick Terminal", "A terminal window opens, a task button appears", settle=2.5, still="01-03-terminal-open", lead=0.4)
    t.press(x, y); t.done()
    t.act("keys", "Type ls with a slip (lss), correct it, then cat friday.md", "ls lists the notes (the slip is deleted before Return); cat prints the Friday list", settle=0.8, still="01-04-shell")
    t.type_human("ls\n", typo_at=2, typo_char="s"); t.wait(1.0); t.type_human("cat friday.md\n", think=(0,)); t.done()
    sx, sy = aim("id:xp-start-HEADLESS-1")
    t.act("pointer", "Slip: open Start and click Chat with a helper by mistake, wanting the Editor", "Start menu opens, then the chat of the helper opens instead of an editor", settle=2.0, still="01-05-slip-chat")
    t.reach(sx, sy); t.click(); t.wait(0.8)
    x, y = aim("id:xp-item-1")
    t.press(x, y); t.done()
    t.flush("slip")
    t.act("key", "Notice it is the chat, press Escape", "The chat closes", settle=1.2, still="01-06-slip-closed")
    t.wait(0.8); t.tap("Escape", 0.2); t.done()
    sx, sy = aim("id:xp-start-HEADLESS-1")
    t.act("pointer", "Start again and pick the Editor", "A text editor opens on friday.md in its own window", settle=3.0, still="01-07-editor-open")
    t.reach(sx, sy); t.click(); t.wait(0.7)
    x, y = aim("id:xp-item-2")
    t.press(x, y); t.done()
    t.act("keys", "Type a line in the editor, then save with Ctrl+O and Return", "The new line is in the text; the editor asks for the file name and keeps it", settle=1.0, still="01-08-editor-typed")
    t.key("ctrl+End"); t.type_human("\n- Monday: plan the week", typo_at=12, typo_char="q"); t.wait(0.8); t.key("ctrl+o"); t.wait(0.9); t.tap("Return", 0.6); t.done()
    t.flush("editor")
    tx, ty = S.centre("id:xp-title-s2", O)
    t.act("pointer", "Drag the title bar of the editor to the right", "The window follows and bends like jelly, then settles", settle=0.3)
    t.reach(tx, ty)
    t.drag(tx, ty, tx + 380, ty + 90, seconds=1.4, hold=0.15, mid_still="01-09-wobbly-drag")
    t.wait(0.8); t.done()
    bx, by = aim("id:xp-task-s1-HEADLESS-1")
    t.act("pointer", "Click the terminal button on the taskbar", "The terminal comes to the front", still="01-10-taskbar-terminal")
    t.press(bx, by); t.done()
    t.act("key", "Open the key list: Super+F1", "A help window lists the keys in groups", settle=1.8, still="01-11-key-list")
    t.key("Super+F1"); t.done()
    t.act("key", "Close the help with Escape", "The help closes, the windows stay", settle=1.0, still="01-12-key-list-closed")
    t.wait(1.5); t.tap("Escape", 0.2); t.done()
    t.flush("voice")
    L.emit("voice.state", {"name": "Atlas", "state": "working", "task": "Tidy notes", "step": 1, "steps": 2, "seq": 4})
    t.wait(3)
    t.act("key", "Press Super+A, the key the list names for the helper", "The chat opens with the helper's transcript", settle=1.8, still="01-13-chat-open")
    t.key("Super+a"); t.done()
    t.flush("chat")
    print("HUD NODES", [n.get("id") for n in S.query("id:hud")], flush=True)
    fx, fy = 1000, 672
    t.act("pointer", "Click into the message field and type", "The field takes the keyboard; the text shows", still="01-15-typed", settle=0.6)
    t.press(fx, fy); t.wait(0.4)
    t.type_human("Please also add Monday.", typo_at=7, typo_char="k"); t.done()
    t.act("key", "Press Return", "The message is sent: the field empties", settle=1.2, still="01-16-sent")
    t.tap("Return", 0.3); t.done()
    t.flush("question")
    L.emit("voice.state", {"name": "Atlas", "state": "question", "task": "Tidy notes", "seq": 5})
    L.emit("voice.confirm", {"id": "51", "prompt": "Atlas wants to write the file notes.txt.", "detail": "~/notes/friday-summary.txt (412 bytes)", "physical": True, "keys": {"yes": "Alt+y", "no": "Alt+n"}, "buttons": True})
    t.wait(1.8)
    t.act("voice event", "The helper asks a question; the person reads it", "A question card with Yes and No shows in the chat", settle=2.0, still="01-17-question", lead=0.2)
    t.done()
    yx, yy = aim("id:hud-card-yes")
    t.act("pointer", "Click Yes", "The click answers the question", settle=1.5, still="01-18-answered")
    t.press(yx, yy); t.done()
    t.flush("answered")
    L.emit("voice.confirm", {"id": "51", "done": True})
    L.emit("voice.state", {"name": "Atlas", "state": "working", "task": "Tidy notes", "step": 2, "steps": 2, "seq": 6})
    cx, cy = aim("id:hud-chat-close")
    t.act("pointer", "Click Close", "The chat closes; only the paperclip stays", settle=1.2, still="01-19-chat-closed", lead=1.2)
    t.press(cx, cy); t.done()
    t.wait(0.5)
    slide(f"{L.dir}/slide.png", 1, "xp", ["A Windows XP desktop on chora.", "Start menu, a terminal, an editor, windows that wobble,", "the key list and the paperclip helper with its chat."])
    t.finish("01-xp.mp4", slide=f"{L.dir}/slide.png")
    json.dump(t.rows, open(f"{OUT}/rows-ch1.json", "w"), indent=1)
finally:
    L.stop()
